function showImagePetalos(container) {
	const encima_petalos = document.getElementById("encima_petalos");
	const encima_petalos_img = document.getElementById("encima_petalos_img");
	const audiopetalos = document.getElementById("petalos");
	const imgSrc = document.getElementById("encima_petalos_img").src;
	encima_petalos_img.src = imgSrc;
	encima_petalos.style.display = "flex";
	audiopetalos.currentTime = 0;
	audiopetalos.play();
}
function hideImagePetalos() {
	const encima_petalos = document.getElementById("encima_petalos");
	const audiopetalos = document.getElementById("petalos");
	encima_petalos.style.display = "none";
	audiopetalos.pause();
}
